/**
 * Icon — draws one of the icons above.
 *
 * Props:
 *   name - the icon's name, e.g. "mic". An unknown name draws nothing.
 *   size - width and height in pixels (default 20)
 */
export default function Icon({ name, size = 20 }) {
  const shapes = ICONS[name];
  if (!shapes) return null;

  // aria-hidden: decoration only, the card's own text says what it is.
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.6"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {shapes}
    </svg>
  );
}
